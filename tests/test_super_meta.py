"""Super image (dynamic partition) metadata parser tests.

Three layers, per AGENTS.md testing rules:

1. Golden fixture: `tests/fixtures/super/golden_super.img` was generated by
   the official AOSP `lpmake` (pinned; see the fixture README) and its SHA-256
   and full parsed structure are pinned here. Runs everywhere.
2. Differential oracle: when the pinned-source `lpmake` binary is on the PATH
   (or `$CAIRN_LPMAKE`), fresh images are generated by the official tool and
   our parse must match exactly what lpmake was told to build. CI runs these
   in the dedicated ubuntu oracle job; locally they skip with a reason.
3. Negative/structural: corrupt checksums, truncation, bad names, and
   duplicate partitions must raise, never guess. Runs everywhere.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import subprocess
from pathlib import Path

import pytest

from cairn.vab.super_meta import (
    BLOCK_DEVICE_SLOT_SUFFIXED,
    HEADER_FLAG_VIRTUAL_AB_DEVICE,
    PARTITION_ATTR_READONLY,
    PARTITION_ATTR_SLOT_SUFFIXED,
    SuperMetadataError,
    parse_super_image,
)

FIXTURE = Path(__file__).parent / "fixtures" / "super" / "golden_super.img"
GOLDEN_SHA256 = "8eef7728358856d4c8cf428d1591b3c1d0c02a9d0bf485b418f167ba0d6d897f"

LPMAKE = os.environ.get("CAIRN_LPMAKE") or shutil.which("lpmake")

pytestmark_oracle = pytest.mark.skipif(
    LPMAKE is None, reason="lpmake oracle not built (see tools/oracle/PINNED.md)"
)


def _zero_image(path: Path, size: int = 65536) -> Path:
    path.write_bytes(b"\x00" * size)
    return path


def test_golden_fixture_sha256_is_pinned() -> None:
    assert hashlib.sha256(FIXTURE.read_bytes()).hexdigest() == GOLDEN_SHA256


def test_golden_fixture_structure() -> None:
    img = parse_super_image(FIXTURE.read_bytes())
    assert img.geometry.metadata_max_size == 4096
    assert img.geometry.metadata_slot_count == 2
    assert img.geometry.logical_block_size == 4096
    assert img.primary_backup_match is True
    assert img.virtual_ab is True
    slot0, slot1 = img.slots
    assert (slot0.major_version, slot0.minor_version) == (10, 2)
    assert slot0.header_flags & HEADER_FLAG_VIRTUAL_AB_DEVICE
    assert [(g.name, g.maximum_size) for g in slot0.groups] == [
        ("default", 0),
        ("tg_a", 524288),
        ("tg_b", 524288),
    ]
    boot_a, system_a = slot0.partitions
    assert boot_a.name == "boot_a"
    assert system_a.name == "system_a"
    assert system_a.attributes & PARTITION_ATTR_READONLY
    assert boot_a.size_bytes == 65536
    assert system_a.size_bytes == 196608
    assert [(e.num_sectors, e.target_type) for e in boot_a.extents] == [(128, 0)]
    assert [(e.num_sectors, e.target_type) for e in system_a.extents] == [(384, 0)]
    # extents map at the device's first logical sector (reserved + metadata)
    device = slot0.block_devices[0]
    assert device.partition_name == "super"
    assert device.size == 1048576
    assert device.first_logical_sector == 56
    assert boot_a.extents[0].target_data == device.first_logical_sector
    assert [p.name for p in slot1.partitions] == ["boot_a", "system_a"]


@pytestmark_oracle
class TestDifferentialAgainstLpmake:
    def test_parse_matches_lpmake_inputs(self, tmp_path: Path) -> None:
        boot = _zero_image(tmp_path / "boot.img")
        system = _zero_image(tmp_path / "system.img", 196608)
        out = tmp_path / "super.img"
        subprocess.run(
            [
                LPMAKE,
                "--metadata-size",
                "4096",
                "--metadata-slots",
                "2",
                "--device-size",
                "1048576",
                "--alignment",
                "4096",
                "--group",
                "tg_a:524288",
                "--group",
                "tg_b:524288",
                "--partition",
                "boot_a:none:65536:tg_a",
                "--image",
                f"boot_a={boot}",
                "--partition",
                "system_a:readonly:196608:tg_a",
                "--image",
                f"system_a={system}",
                "--virtual-ab",
                "--output",
                str(out),
            ],
            check=True,
            capture_output=True,
        )
        img = parse_super_image(out.read_bytes())
        assert img.geometry.metadata_max_size == 4096
        assert img.geometry.metadata_slot_count == 2
        assert img.geometry.logical_block_size == 4096
        assert img.virtual_ab is True
        assert img.primary_backup_match is True
        slot = img.slots[0]
        by_name = {p.name: p for p in slot.partitions}
        assert set(by_name) == {"boot_a", "system_a"}
        assert by_name["boot_a"].size_bytes == 65536
        assert by_name["system_a"].size_bytes == 196608
        assert by_name["system_a"].attributes & PARTITION_ATTR_READONLY
        groups = {g.name: g for g in slot.groups}
        assert groups["tg_a"].maximum_size == 524288
        assert groups["tg_b"].maximum_size == 524288
        assert by_name["boot_a"].group_index == slot.groups.index(groups["tg_a"])
        assert slot.block_devices[0].size == 1048576

    def test_parse_matches_lpmake_super_empty_layout(self, tmp_path: Path) -> None:
        out = tmp_path / "super_empty.img"
        subprocess.run(
            [
                LPMAKE,
                "--metadata-size",
                "4096",
                "--metadata-slots",
                "2",
                "--device-size",
                "auto",
                "--alignment",
                "4096",
                "--group",
                "tg:262144",
                "--partition",
                "boot_a:none:65536:tg",
                "--output",
                str(out),
            ],
            check=True,
            capture_output=True,
        )
        img = parse_super_image(out.read_bytes())
        assert img.geometry.metadata_slot_count == 2
        slot = img.slots[0]
        assert [p.name for p in slot.partitions] == ["boot_a"]
        assert slot.partitions[0].size_bytes == 65536

    def test_parse_matches_lpmake_slot_suffixing(self, tmp_path: Path) -> None:
        boot = _zero_image(tmp_path / "boot.img")
        out = tmp_path / "suffixed.img"
        subprocess.run(
            [
                LPMAKE,
                "--metadata-size",
                "4096",
                "--metadata-slots",
                "2",
                "--device-size",
                "1048576",
                "--alignment",
                "4096",
                "--partition",
                "boot:none:65536",
                "--image",
                f"boot={boot}",
                "--auto-slot-suffixing",
                "--output",
                str(out),
            ],
            check=True,
            capture_output=True,
        )
        img = parse_super_image(out.read_bytes())
        slot = img.slots[0]
        assert slot.partitions[0].attributes & PARTITION_ATTR_SLOT_SUFFIXED
        assert slot.block_devices[0].flags & BLOCK_DEVICE_SLOT_SUFFIXED


class TestNegative:
    def test_rejects_garbage(self) -> None:
        with pytest.raises(SuperMetadataError, match=r"geometry magic"):
            parse_super_image(b"\x00" * 8192)

    def test_rejects_truncated_image(self) -> None:
        data = bytearray(FIXTURE.read_bytes()[:200])
        with pytest.raises(SuperMetadataError, match="geometry magic"):
            parse_super_image(bytes(data))

    def test_rejects_corrupt_geometry_checksum(self) -> None:
        data = bytearray(FIXTURE.read_bytes())
        data[4096 + 20] ^= 0xFF
        with pytest.raises(SuperMetadataError, match="geometry checksum"):
            parse_super_image(bytes(data))

    def test_rejects_corrupt_header_checksum(self) -> None:
        data = bytearray(FIXTURE.read_bytes())
        data[12288 + 16] ^= 0xFF
        with pytest.raises(SuperMetadataError, match="header checksum"):
            parse_super_image(bytes(data))

    def test_rejects_corrupt_tables(self) -> None:
        data = bytearray(FIXTURE.read_bytes())
        data[12288 + 300] ^= 0xFF
        with pytest.raises(SuperMetadataError, match="tables checksum"):
            parse_super_image(bytes(data))
